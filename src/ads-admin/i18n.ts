export function getInitialLanguage(): Language {
  const saved = localStorage.getItem(LANGUAGE_KEY);
  return saved === 'en' ? 'en' : 'zh';
}

export function saveLanguage(language: Language): void {
  localStorage.setItem(LANGUAGE_KEY, language);
}

export function translateText(value: string, language: Language): string {
  if (language === 'zh' || !value.trim()) return value;
  const leading = value.match(/^\s*/)?.[0] ?? '';
  const trailing = value.match(/\s*$/)?.[0] ?? '';
  const trimmed = value.trim();
  const exact = exactTranslations[trimmed];
  if (exact) return `${leading}${exact}${trailing}`;
  let translated = trimmed;
  for (const [pattern, replacement] of replacements) translated = translated.replace(pattern, replacement);
  return `${leading}${translated}${trailing}`;
}

export function localizeElement(root: HTMLElement, language: Language): void {
  if (language === 'zh') return;
  root.querySelectorAll<HTMLOptionElement>('option:not([value])').forEach(option => option.value = option.textContent?.trim() ?? '');
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  let node = walker.nextNode();
  while (node) {
    const parent = node.parentElement;
    if (parent && !parent.closest('[data-i18n-skip]') && !['SCRIPT', 'STYLE', 'CODE', 'PRE'].includes(parent.tagName)) {
      node.nodeValue = translateText(node.nodeValue ?? '', language);
    }
    node = walker.nextNode();
  }
  root.querySelectorAll<HTMLElement>('[aria-label], [placeholder], [title]').forEach(element => {
    for (const attribute of ['aria-label', 'placeholder', 'title']) {
      const value = element.getAttribute(attribute);
      if (value) element.setAttribute(attribute, translateText(value, language));
    }
  });
}

export function localizeDocument(language: Language): void {
  document.documentElement.lang = language === 'en' ? 'en' : 'zh-CN';
  document.title = language === 'en' ? 'Spark Ads · Ads Management' : '星火推广 · 广告管理后台';
  const description = document.querySelector<HTMLMetaElement>('meta[name="description"]');
  if (description) description.content = language === 'en'
    ? 'Advertising management for campaigns, ad groups, creative, and reports.'
    : '广告推广管理后台，用于管理推广计划、广告组、素材与数据报告。';
}
